-- Run once in Supabase Dashboard -> SQL Editor.
-- Lets you (the site owner) see who uses the app and basic activity:
-- sign-ins, saved pictures, saved frames. It does NOT store photo pixels
-- or the pictures themselves -- those stay in the "booth" / "frames"
-- storage buckets, governed by their own policies.

-- One row per user, flagging who may view the admin dashboard.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  is_admin boolean not null default false,
  created_at timestamptz not null default now()
);
alter table public.profiles enable row level security;

drop policy if exists "profiles: read own"   on public.profiles;
drop policy if exists "profiles: admin read" on public.profiles;
drop policy if exists "profiles: insert own" on public.profiles;

create policy "profiles: read own"   on public.profiles for select to authenticated
  using (id = auth.uid());
create policy "profiles: admin read" on public.profiles for select to authenticated
  using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.is_admin));
create policy "profiles: insert own" on public.profiles for insert to authenticated
  with check (id = auth.uid());

-- Activity log: who did what and when. "meta" holds small, non-sensitive
-- details only (a frame's name, a layout id) -- never image data.
create table if not exists public.app_events (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  email text,
  event text not null,
  meta jsonb,
  created_at timestamptz not null default now()
);
alter table public.app_events enable row level security;

drop policy if exists "events: insert own"  on public.app_events;
drop policy if exists "events: admin read"  on public.app_events;

create policy "events: insert own" on public.app_events for insert to authenticated
  with check (user_id = auth.uid());
create policy "events: admin read" on public.app_events for select to authenticated
  using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.is_admin));

